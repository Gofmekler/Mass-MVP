"""Справочник химических элементов: средние атомные массы и изотопный состав.

Изотопный состав задан только для элементов, входящих в сплавы задания 3;
для остальных используется одна средняя атомная масса.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Isotope:
    mass_number: int
    mass: float        # а.е.м.
    abundance: float   # доля, сумма по элементу = 1


@dataclass(frozen=True)
class Element:
    symbol: str
    name: str
    mass: float                       # средняя атомная масса, а.е.м.
    isotopes: tuple = ()              # tuple[Isotope, ...]

    def isotope_peaks(self):
        """Пары (масса, доля); без изотопных данных — одна средняя масса."""
        if not self.isotopes:
            return ((self.mass, 1.0),)
        return tuple((i.mass, i.abundance) for i in self.isotopes)


def _iso(*items):
    """items: (массовое число, масса, распространённость в %)."""
    total = sum(p for _, _, p in items)
    return tuple(Isotope(a, m, p / total) for a, m, p in items)



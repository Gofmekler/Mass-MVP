class TourPresenter:
    def __init__(self, view, steps=TOUR_STEPS):
        self._view = view
        self._steps = steps
        self._current = ()
        self._index = 0
        self._seen = set()
        view.tour_next.connect(self._on_next)
        view.tour_skip.connect(self.stop)

    @property
    def active(self):
        return bool(self._current)

    def has_tour(self, page):
        return page in self._steps

    def reset(self):
        self._seen = set()
        self.stop()

    def start_if_new(self, page):
        if page in self._steps and page not in self._seen:
            self.start(page)

    def start(self, page):
        if page not in self._steps:
            return
        self._seen.add(page)
        self._current = self._steps[page]
        self._index = 0
        self._show()

    def stop(self):
        if self._current:
            self._current = ()
            self._view.hide_tour()

    def _show(self):
        step = self._current[self._index]
        self._view.show_tour_step(step.target, step.title, step.text,
                                  self._index + 1, len(self._current))

    def _on_next(self):
        if not self._current:
            return
        self._index += 1
        if self._index >= len(self._current):
            self.stop()
        else:
            self._show()
